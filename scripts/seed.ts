// Writes sync-server/seed.sql with the built-in places (src/data/places.ts), ready for:
//   npx wrangler d1 execute sapasense --remote --file=sync-server/seed.sql
import { writeFileSync } from 'node:fs'
import { PLACES } from '../src/data/places'

const q = (s: string) => "'" + s.replace(/'/g, "''") + "'"
const now = Date.now()
const rows = PLACES.map((p, i) => `INSERT OR REPLACE INTO places (id, sort, json, updated_at) VALUES (${q(p.id)}, ${i}, ${q(JSON.stringify(p))}, ${now});`)
writeFileSync(new URL('../sync-server/seed.sql', import.meta.url), '-- generated by scripts/seed.ts — do not edit\n' + rows.join('\n') + '\n')
console.log(`seed.sql: ${rows.length} places`)
